/**
 * Private-GitHub-repository storage for the key roster.
 *
 * The Worker keeps the strongly consistent runtime copy in a Durable Object; this
 * module writes the human-readable, durable roster to a single file in a PRIVATE
 * repository that you own:
 *
 *   keys.js   – one comment line per key:  ht-3jhnnuj2tg - John Doe - johndoe@…
 *               plus a machine-readable array of salted SHA-256 hashes, owner
 *               metadata and usage rollups. No plaintext key is ever written here
 *               unless you deliberately enable KEY_ESCROW_SECRET (see README).
 *   byok.js   – AES-GCM ciphertexts of user Groq keys, plus owner uid/ref.
 *
 * The GitHub token only needs "Contents: read and write" on that one repository.
 * Reads are used to bootstrap an empty Durable Object (e.g. after a reset) and to
 * skip no-op writes.
 */

import { bytesToBase64, base64ToBytes } from './util.mjs';
import { keyLabel } from './keys.mjs';

export function githubConfigured(env) {
  return Boolean(env.GITHUB_TOKEN && env.GITHUB_REPO);
}

function apiUrl(env, path) {
  const repo = env.GITHUB_REPO;
  const file = path || env.GITHUB_KEYS_PATH || 'keys.js';
  const branch = env.GITHUB_BRANCH || 'main';
  return `https://api.github.com/repos/${repo}/contents/${encodeURI(file)}?ref=${encodeURIComponent(branch)}`;
}

function authHeaders(env) {
  return {
    authorization: `Bearer ${env.GITHUB_TOKEN}`,
    accept: 'application/vnd.github+json',
    'x-github-api-version': '2022-11-28',
    'user-agent': 'htmltools-me-ai-api',
  };
}

/** @returns {Promise<{content:string, sha:string}|null>} */
export async function readRepoFile(env, path, fetchImpl = fetch) {
  if (!githubConfigured(env)) return null;
  const res = await fetchImpl(apiUrl(env, path), {
    headers: authHeaders(env),
    cache: 'no-store',
    cf: { cacheTtl: 0 },
  });
  if (res.status === 404) return null;
  if (!res.ok) throw new Error(`GitHub read failed (${res.status}).`);
  const body = await res.json();
  const content = new TextDecoder().decode(base64ToBytes(String(body.content || '').replace(/\n/g, '')));
  return { content, sha: body.sha };
}

export async function writeRepoFile(env, path, content, message, fetchImpl = fetch) {
  if (!githubConfigured(env)) return { skipped: true };
  const file = path || env.GITHUB_KEYS_PATH || 'keys.js';
  const branch = env.GITHUB_BRANCH || 'main';
  const existing = await readRepoFile(env, file, fetchImpl);
  if (existing && existing.content === content) return { unchanged: true };

  const put = async sha => fetchImpl(
    `https://api.github.com/repos/${env.GITHUB_REPO}/contents/${encodeURI(file)}`,
    {
      method: 'PUT',
      headers: { ...authHeaders(env), 'content-type': 'application/json' },
      body: JSON.stringify({
        message: `${message} [skip ci]`,
        content: bytesToBase64(new TextEncoder().encode(content)),
        branch,
        ...(sha ? { sha } : {}),
      }),
    },
  );

  let res = await put(existing?.sha);
  if (res.status === 409) {
    // Someone else (or a previous retry) wrote the file; re-read and retry once.
    const fresh = await readRepoFile(env, file, fetchImpl);
    res = await put(fresh?.sha);
  }
  if (!res.ok) {
    const text = await res.text().catch(() => '');
    throw new Error(`GitHub write failed (${res.status}). ${text.slice(0, 200)}`);
  }
  return { written: true };
}

const header = () => [
  '// htmltools.me AI API — PRIVATE key roster.',
  '//',
  '// Generated by the gateway Worker. Do not edit by hand: the next sync overwrites',
  '// it. Plaintext API keys are NOT stored here — each record keeps a salted',
  '// SHA-256 hash. The full key is shown to its owner exactly once, at creation.',
  '//',
  '// Format: <key id> - <display name> - <email>',
  '',
].join('\n');

/** Render the private roster file. `records` must already be sanitised by the DO. */
export function renderKeysFile(records, meta = {}) {
  const lines = [header()];
  const active = records.filter(r => !r.revoked);
  lines.push(...active.map(r => `// ${keyLabel(r)}`));
  if (!active.length) lines.push('// (no active keys)');
  lines.push('');
  lines.push('/* eslint-disable */');
  lines.push('module.exports = ' + JSON.stringify({
    generated: new Date().toISOString(),
    gateway: 'htmltools-me-ai-api',
    count: records.length,
    active: active.length,
    day: meta.day || null,
    pool: meta.pool || null,
    keys: records.map(r => ({
      id: r.id,
      salt: r.salt,
      hash: r.hash,
      uid: r.uid,
      name: r.name,
      email: r.email,
      label: r.label || '',
      created: r.created,
      lastUsed: r.lastUsed || null,
      revoked: Boolean(r.revoked),
      revokedAt: r.revokedAt || null,
      usage: r.usage || { requests: 0, tokens: 0 },
      ...(r.escrow ? { escrow: r.escrow } : {}),
    })),
  }, null, 2) + ';\n');
  return lines.join('\n');
}

export function renderByokFile(records) {
  return [
    '// htmltools.me AI API — PRIVATE BYOK ciphertext store.',
    '//',
    '// Each entry is an AES-256-GCM ciphertext of a user-supplied Groq API key. The',
    '// encryption secret lives only in a Cloudflare Worker secret and is not in this',
    '// repository. Deleting an entry removes that user\'s stored provider key.',
    '',
    '/* eslint-disable */',
    'module.exports = ' + JSON.stringify({
      generated: new Date().toISOString(),
      cipher: 'AES-256-GCM/HKDF-SHA-256',
      providers: records.map(r => ({
        uid: r.uid,
        ref: r.ref,
        provider: r.provider,
        blob: r.blob,
        updated: r.updated,
        verified: Boolean(r.verified),
      })),
    }, null, 2) + ';\n',
  ].join('\n');
}

/** Best-effort parse of a previously written roster, used to seed an empty DO. */
export function parseKeysFile(content) {
  if (!content) return [];
  const start = content.indexOf('module.exports =');
  if (start < 0) return [];
  const body = content.slice(start + 'module.exports ='.length).replace(/;\s*$/, '');
  try {
    const data = JSON.parse(body);
    const keys = Array.isArray(data?.keys) ? data.keys : [];
    return keys
      .filter(k => typeof k.id === 'string' && typeof k.hash === 'string' && typeof k.salt === 'string')
      .map(k => ({
        id: k.id.slice(0, 16),
        salt: k.salt,
        hash: k.hash,
        uid: String(k.uid || '').slice(0, 128),
        name: String(k.name || '').slice(0, 80),
        email: String(k.email || '').slice(0, 254),
        label: typeof k.label === 'string' ? k.label.slice(0, 80) : '',
        created: Number(k.created) || Date.now(),
        lastUsed: Number(k.lastUsed) || null,
        revoked: Boolean(k.revoked),
        revokedAt: Number(k.revokedAt) || null,
        usage: {
          requests: Number(k.usage?.requests) || 0,
          tokens: Number(k.usage?.tokens) || 0,
        },
        ...(k.escrow ? { escrow: k.escrow } : {}),
      }));
  } catch {
    return [];
  }
}

export function parseByokFile(content) {
  if (!content) return [];
  const start = content.indexOf('module.exports =');
  if (start < 0) return [];
  try {
    const data = JSON.parse(content.slice(start + 'module.exports ='.length).replace(/;\s*$/, ''));
    return Array.isArray(data?.providers) ? data.providers : [];
  } catch {
    return [];
  }
}
